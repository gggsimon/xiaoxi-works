/* 十神计算（全局版，工具内同名单为各自遮蔽实现） */
function shiShenOf(gan, dayGan) {
  const GW = {甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土', 己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水'};
  const GEN = {木: '火', 火: '土', 土: '金', 金: '水', 水: '木'};
  const KO = {木: '土', 土: '水', 水: '火', 火: '金', 金: '木'};
  const gIdx = g => '甲乙丙丁戊己庚辛壬癸'.indexOf(g);
  const me = GW[dayGan], other = GW[gan];
  const sameP = (gIdx(gan) % 2) === (gIdx(dayGan) % 2);
  if (!me || !other) return '';
  if (other === me) return sameP ? '比肩' : '劫财';
  if (GEN[other] === me) return sameP ? '偏印' : '正印';
  if (GEN[me] === other) return sameP ? '食神' : '伤官';
  if (KO[other] === me) return sameP ? '七杀' : '正官';
  if (KO[me] === other) return sameP ? '偏财' : '正财';
  return '';
}

