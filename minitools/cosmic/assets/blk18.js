  const upperTri = TRI_NAME[hex.lines.slice(3,6).join('')];
  const ganL = TRI_GAN[lowerTri], ganU = TRI_GAN[upperTri];
  const zhiAll = TRI_ZHI[lowerTri].slice(0,3).concat(TRI_ZHI[upperTri].slice(3,6));
  /* 六亲按本宫五行 */
  const yao = [];
  for (let i = 0; i < 6; i++) {
    yao.push({
      pos: i+1,
      yang: hex.lines[i] === 1,
      zhi: zhiAll[i],
      gan: i < 3 ? ganL[0] : (ganU[1] || ganU[0]),
      qin: liuQin(pe, zhiAll[i]),
      shi: hex.shi === i+1, ying: hex.ying === i+1,
      moving: moving.includes(i)
    });
  }
  /* 六兽（按日干起） */
  const BEASTS = {甲:'青龙',乙:'青龙',丙:'朱雀',丁:'朱雀',戊:'勾陈',己:'腾蛇',庚:'白虎',辛:'白虎',壬:'玄武',癸:'玄武'};
